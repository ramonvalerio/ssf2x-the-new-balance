local out = assert(io.open("D:/repos/SuperStreetFighter2X_Update/work/emutest/out/api_probe.txt", "w"))
local function try(name, fn)
  local ok, err = pcall(fn)
  out:write(name .. ": " .. (ok and "OK" or ("ERRO: " .. tostring(err))) .. "\n")
end
try("memory.registerwrite", function() memory.registerwrite(0xFF84D6, function(a, v) end) end)
try("memory.registerexec", function() memory.registerexec(0x100, function() end) end)
try("cpu table", function() local x = cpu.getregister("pc") end)
try("m68k table", function() local x = m68k.getregister("pc") end)
try("memory.getregister pc", function()
  local x = memory.getregister("pc")
  out:write("  valor: " .. tostring(x) .. "\n")
end)
try("memory.getregister PC", function()
  local x = memory.getregister("PC")
  out:write("  valor: " .. tostring(x) .. "\n")
end)
try("memory.getregister(0,pc)", function()
  local x = memory.getregister(0, "pc")
  out:write("  valor: " .. tostring(x) .. "\n")
end)
try("listar globals memory.*", function()
  for k, v in pairs(memory) do out:write("  memory." .. tostring(k) .. " = " .. type(v) .. "\n") end
end)
out:close()
